// ============================================================================
// alu_tb.cpp : self-checking C++ testbench for src/core/humber_alu.sv
//
// HOW THIS WORKS (read this first)
//   Verilator turns humber_alu.sv into a C++ class called Vhumber_alu.
//   Every port of the module becomes a public member of that class:
//        input  op, a, b   -> we WRITE these:  dut.op = ...;  dut.a = ...;
//        output result     -> we READ this:    dut.result
//   The ALU is purely combinational: there is no clock and no state. So a
//   test is just: set inputs, call dut.eval() so Verilator recomputes the
//   outputs, then compare dut.result with what we EXPECT.
//
//   "What we expect" comes from reference_alu() below: a second, independent
//   implementation of the same ten operations written in plain C++. If the
//   RTL and the reference disagree, one of them is wrong, and the failure
//   message tells you which op and which operands to look at.
//
//   The testbench returns exit code 0 only if EVERY check passed, so
//   `make run` fails (non-zero) when the ALU is broken. A test that only
//   prints something and always exits 0 would never fail in CI.
// ============================================================================

#include "Vhumber_alu.h"   // generated by Verilator from humber_alu.sv
#include "verilated.h"     // Verilator runtime (commandArgs, etc.)

#include <cstdint>
#include <cstdio>
#include <cstdlib>         // srand / rand

// ----------------------------------------------------------------------------
// Opcode numbers
//
// These MUST match the order of the enum in src/core/humber_pkg.sv. In the
// package we wrote `typedef enum logic [3:0] { ALU_ADD, ALU_SUB, ... }` with
// no explicit values, so SystemVerilog numbers them 0, 1, 2, ... in the order
// listed. The C++ side only sees plain integers, so we mirror that order here.
//
// WARNING: if you reorder or add ops in humber_pkg.sv, update this list too,
// or the test will exercise the wrong operations. (A later improvement is to
// give the package explicit values, e.g. ALU_ADD = 4'd0, so the numbers are
// written down in one obvious place instead of implied by order.)
// ----------------------------------------------------------------------------
enum AluOp : uint8_t {
    OP_ADD  = 0,
    OP_SUB  = 1,
    OP_SLL  = 2,
    OP_SLT  = 3,
    OP_SLTU = 4,
    OP_XOR  = 5,
    OP_SRL  = 6,
    OP_SRA  = 7,
    OP_OR   = 8,
    OP_AND  = 9,
    // The enum is 4 bits wide, so 10..15 are legal bit patterns that name no
    // operation. The RTL's `default:` branch returns 0 for them. We test that
    // too, because "what happens on an illegal opcode" is behaviour somebody
    // can depend on (and a latch would show up here).
    OP_FIRST_ILLEGAL = 10,
    OP_LAST_ILLEGAL  = 15
};

static const char* op_name(uint8_t op) {
    switch (op) {
        case OP_ADD:  return "ADD";
        case OP_SUB:  return "SUB";
        case OP_SLL:  return "SLL";
        case OP_SLT:  return "SLT";
        case OP_SLTU: return "SLTU";
        case OP_XOR:  return "XOR";
        case OP_SRL:  return "SRL";
        case OP_SRA:  return "SRA";
        case OP_OR:   return "OR";
        case OP_AND:  return "AND";
        default:      return "ILLEGAL";
    }
}

// ----------------------------------------------------------------------------
// Reference model: what the RISC-V spec says each op must produce.
//
// Written deliberately DIFFERENTLY from the RTL where it matters, so one
// shared misunderstanding can't hide in both. All values are uint32_t
// (unsigned 32-bit) so C++ arithmetic wraps modulo 2^32 exactly like hardware.
// ----------------------------------------------------------------------------
static uint32_t reference_alu(uint8_t op, uint32_t a, uint32_t b) {
    // RV32: only the low 5 bits of b are the shift amount (0..31).
    const uint32_t shamt = b & 0x1F;

    switch (op) {
        case OP_ADD:  return a + b;   // unsigned wraparound == two's-complement add
        case OP_SUB:  return a - b;   // same for subtract

        case OP_SLL:  return a << shamt;   // zero fill from the right
        case OP_SRL:  return a >> shamt;   // unsigned >> is a logical shift: zero fill

        case OP_SRA: {
            // Arithmetic shift right: vacated top bits copy the sign bit (a[31]).
            // We build it by hand instead of using (int32_t)a >> shamt, because
            // right-shifting a negative signed value was "implementation
            // defined" in older C++. Doing it manually also means this model
            // does not share the `$signed(a) >>>` idea with the RTL.
            //   logical = a >> shamt                      (zeros on top)
            //   mask    = ~(0xFFFFFFFF >> shamt)          (ones in the top shamt bits)
            // If a is negative, OR the mask in to turn those zeros into ones.
            uint32_t logical = a >> shamt;
            uint32_t mask    = ~(0xFFFFFFFFu >> shamt);   // shamt==0 -> mask is 0, fine
            return (a & 0x80000000u) ? (logical | mask) : logical;
        }

        case OP_SLT:  // signed compare. Reinterpret the same bits as int32_t.
            return ((int32_t)a < (int32_t)b) ? 1u : 0u;
        case OP_SLTU: // unsigned compare. Plain uint32_t comparison.
            return (a < b) ? 1u : 0u;

        case OP_XOR:  return a ^ b;
        case OP_OR:   return a | b;
        case OP_AND:  return a & b;

        default:      return 0u;   // illegal opcode: RTL `default:` gives 0
    }
}

// ----------------------------------------------------------------------------
// Test bookkeeping
// ----------------------------------------------------------------------------
static Vhumber_alu dut;          // the design under test (one instance)
static unsigned long n_checks = 0;
static unsigned long n_fails  = 0;

// Apply one stimulus to the DUT and compare against the reference.
//   `why` is a short label that appears in the failure message so you can tell
//   which directed test (or "random") produced the failing case.
static void check(uint8_t op, uint32_t a, uint32_t b, const char* why) {
    dut.op = op;
    dut.a  = a;
    dut.b  = b;
    dut.eval();   // recompute combinational outputs. WITHOUT this, dut.result
                  // still holds the previous answer and tests would "pass" or
                  // "fail" for the wrong reason.

    const uint32_t got = dut.result;
    const uint32_t exp = reference_alu(op, a, b);
    n_checks++;

    if (got != exp) {
        n_fails++;
        // Cap printing so a badly broken ALU doesn't bury the first (most
        // useful) failures under thousands of lines.
        if (n_fails <= 20) {
            printf("FAIL [%s] %-4s a=0x%08x b=0x%08x  got=0x%08x  expected=0x%08x\n",
                   why, op_name(op), a, b, got, exp);
        }
    }
}

// ----------------------------------------------------------------------------
// Directed tests: hand-picked inputs aimed at the classic ALU bugs.
// ----------------------------------------------------------------------------
static void directed_tests() {
    // --- SLT vs SLTU: same bits, different meaning ---------------------------
    // 0xFFFFFFFF is -1 signed but 4294967295 unsigned.
    check(OP_SLT,  0xFFFFFFFFu, 0x00000001u, "slt  -1 < 1");        // signed:   1
    check(OP_SLTU, 0xFFFFFFFFu, 0x00000001u, "sltu max < 1");       // unsigned: 0
    // Most negative vs most positive 32-bit signed number.
    check(OP_SLT,  0x80000000u, 0x7FFFFFFFu, "slt  min < max");     // 1
    check(OP_SLTU, 0x80000000u, 0x7FFFFFFFu, "sltu 2^31 < 2^31-1"); // 0
    check(OP_SLT,  0x00000005u, 0x00000005u, "slt  equal");         // 0 (strict <)
    check(OP_SLTU, 0x00000005u, 0x00000005u, "sltu equal");         // 0

    // --- SRA vs SRL: the sign bit decides ------------------------------------
    check(OP_SRA, 0x80000000u, 1,  "sra  neg by 1");   // 0xC0000000
    check(OP_SRL, 0x80000000u, 1,  "srl  neg by 1");   // 0x40000000
    check(OP_SRA, 0x80000000u, 31, "sra  neg by 31");  // 0xFFFFFFFF
    check(OP_SRL, 0x80000000u, 31, "srl  neg by 31");  // 0x00000001
    check(OP_SRA, 0x40000000u, 1,  "sra  pos by 1");   // positive: same as SRL
    check(OP_SRA, 0xFFFFFFFFu, 4,  "sra  -1 stays -1");

    // --- Shift amount edge cases ---------------------------------------------
    // Shift by 0 must return the input unchanged.
    check(OP_SLL, 0xDEADBEEFu, 0,  "sll  by 0");
    check(OP_SRL, 0xDEADBEEFu, 0,  "srl  by 0");
    check(OP_SRA, 0xDEADBEEFu, 0,  "sra  by 0");
    // Only b[4:0] counts. b = 0x21 = 33 = 0b100001: low 5 bits are 1, so the
    // shift is by 1. A buggy `a << b` would shift by 33 and give 0.
    check(OP_SLL, 0x00000001u, 0x00000021u, "sll  mask b=33 -> by 1");
    check(OP_SRL, 0x80000000u, 0x00000021u, "srl  mask b=33 -> by 1");
    check(OP_SRA, 0x80000000u, 0x00000021u, "sra  mask b=33 -> by 1");
    // b = 32: low 5 bits are 0, so NO shift (not "shift everything out").
    check(OP_SLL, 0x12345678u, 0x00000020u, "sll  mask b=32 -> by 0");
    // Upper bits of b set but low 5 bits zero.
    check(OP_SLL, 0x00000001u, 0xFFFFFFE0u, "sll  b upper bits only");

    // --- ADD / SUB wraparound -------------------------------------------------
    check(OP_ADD, 0xFFFFFFFFu, 0x00000001u, "add  wraps to 0");
    check(OP_ADD, 0x7FFFFFFFu, 0x00000001u, "add  signed overflow");
    check(OP_SUB, 0x00000000u, 0x00000001u, "sub  0-1 wraps");
    check(OP_SUB, 0x80000000u, 0x00000001u, "sub  min-1 wraps");
    check(OP_SUB, 0x12345678u, 0x12345678u, "sub  x-x = 0");

    // --- Bitwise sanity --------------------------------------------------------
    check(OP_AND, 0xF0F0F0F0u, 0xFF00FF00u, "and");
    check(OP_OR,  0xF0F0F0F0u, 0x0F0F0F0Fu, "or");
    check(OP_XOR, 0xFFFFFFFFu, 0xAAAAAAAAu, "xor");

    // --- Illegal opcodes: RTL default branch must give 0 ----------------------
    for (uint8_t op = OP_FIRST_ILLEGAL; op <= OP_LAST_ILLEGAL; op++) {
        check(op, 0xFFFFFFFFu, 0xFFFFFFFFu, "illegal op");
    }
}

// ----------------------------------------------------------------------------
// Random tests.
//
// Purely uniform random 32-bit values almost never hit the interesting
// corners (0, 0xFFFFFFFF, 0x80000000, ...). So pick_operand() flips a coin:
// half the time return a known corner value, half the time a random value.
// ----------------------------------------------------------------------------
static uint32_t rand32() {
    // rand() only guarantees 15 bits, so stitch three calls into 32 bits.
    return ((uint32_t)rand() << 17) ^ ((uint32_t)rand() << 8) ^ (uint32_t)rand();
}

static uint32_t pick_operand() {
    static const uint32_t corners[] = {
        0x00000000u, 0x00000001u, 0x7FFFFFFFu, 0x80000000u,
        0x80000001u, 0xFFFFFFFFu, 0xFFFFFFFEu, 0x0000001Fu,
        0x00000020u, 0x55555555u, 0xAAAAAAAAu
    };
    const unsigned n = sizeof(corners) / sizeof(corners[0]);
    if (rand() & 1) return corners[rand() % n];
    return rand32();
}

static void random_tests(unsigned count) {
    for (unsigned i = 0; i < count; i++) {
        // Ops 0..9 are legal. (Illegal ones are covered by the directed test.)
        const uint8_t op = (uint8_t)(rand() % 10);
        check(op, pick_operand(), pick_operand(), "random");
    }
}

// ----------------------------------------------------------------------------
int main(int argc, char** argv) {
    Verilated::commandArgs(argc, argv);

    // Fixed seed => the same "random" sequence every run. A failure you see
    // once is a failure you can reproduce. (Change the number to explore.)
    srand(1);

    directed_tests();
    random_tests(100000);

    printf("%lu checks, %lu failures\n", n_checks, n_fails);
    printf(n_fails == 0 ? "PASS\n" : "FAIL\n");

    dut.final();                   // let Verilator clean up
    return n_fails == 0 ? 0 : 1;   // non-zero exit makes `make` report failure
}
